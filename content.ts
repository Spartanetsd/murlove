/** Підхоплює правки з personal.json (якщо файл є і він коректний). */
export function applyPersonal(p: PersonalFile) {
  const str = (v: unknown) => (typeof v === 'string' && v.trim() ? v.trim() : null)
  const h = str(p.homeMessage)
  if (h) PERSONAL.homeMessage = h
  const g = str(p.hugMessage)
  if (g) PERSONAL.hugMessage = g
  if (Array.isArray(p.confession) && p.confession.some((x) => str(x))) PERSONAL.confession = p.confession.filter((x) => str(x)).map(String)
  const cs = str(p.confessionSign)
  if (cs) PERSONAL.confessionSign = cs
  const d = str(p.ourDate)
  if (d && /^\d{4}-\d{2}-\d{2}$/.test(d)) PERSONAL.ourDate = d
  const list = (v: unknown) => (Array.isArray(v) ? v.filter((x) => str(x)).map((x) => String(x).trim()) : [])
  const extra = list(p.extraLove)
  if (extra.length) LOVE.push(...extra)
  const reasons = list(p.myReasons)
  if (reasons.length) {
    // особисті причини — першими; загалом лишається рівно 100
    REASONS.unshift(...reasons)
    if (REASONS.length > 100 && reasons.length < 100) REASONS.length = 100
    PERSONAL.reasonsCount = Math.min(reasons.length, REASONS.length)
  }
  const notes = list(p.myNotes)
  if (notes.length) DAILY.unshift(...notes)
  const sorry = list(p.myApologies)
  if (sorry.length) {
    APOLOGIES.unshift(...sorry)
    PERSONAL.apologyCount = sorry.length
  }
}

